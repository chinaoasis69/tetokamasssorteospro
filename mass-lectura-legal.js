  function ficha(codigo) {
    return Object.hasOwn(documentos, codigo) ? documentos[codigo] : null;
  }

  // A reading translation applies only to the Spanish text it was prepared from.
  function mismaEdicion(a, b) {
    const normalizar = valor => String(valor).replace(/\r\n?/g, "\n").trim();
    return normalizar(a) === normalizar(b);
  }

  const vistas = new WeakMap();
  function pintar(cuerpo) {
    const vista = vistas.get(cuerpo);
    if (!vista) return;
    const ingles = window.MassIdioma?.actual === "en";
    const traducido = ingles && !vista.verOriginal;
    cuerpo.textContent = traducido ? vista.ficha.en : vista.original;
    cuerpo.lang = traducido ? "en" : "es";
    vista.etiqueta.textContent = traducido ? "English translation" : ingles ? "Spanish original" : "Original en español";
    vista.boton.hidden = !ingles;
    vista.boton.textContent = traducido ? "Read Spanish original" : "Read in English";
  }

  function mostrar(cuerpo, etiqueta, original) {
    vistas.delete(cuerpo);
    cuerpo.removeAttribute("data-mass-lectura-legal");
    const registro = Object.values(documentos).find(doc => mismaEdicion(original, doc.es));
    if (!registro) return false;
    const titulo = document.createElement("span");
    const boton = document.createElement("button");
    boton.type = "button";
    boton.style.marginInlineStart = ".75em";
    const vista = {ficha: registro, original, etiqueta: titulo, boton, verOriginal: false};
    vistas.set(cuerpo, vista);
    cuerpo.dataset.massLecturaLegal = "";
    etiqueta.replaceChildren(titulo, " ", boton);
    boton.onclick = () => {
      vista.verOriginal = !vista.verOriginal;
      pintar(cuerpo);
    };
    pintar(cuerpo);
    return true;
  }

  document.addEventListener("mass:idioma", () => {
    document.querySelectorAll("[data-mass-lectura-legal]").forEach(cuerpo => {
      const vista = vistas.get(cuerpo);
      if (!vista) return;
      vista.verOriginal = false;
      pintar(cuerpo);
    });
  });

  document.addEventListener("click", evento => {
    const copiar = evento.target.closest?.("[data-copiar-reglas]");
    if (copiar) {
      const original = copiar.parentElement.querySelector("[data-original-reglas]");
      if (!original) return;
      const estado = copiar.parentElement.querySelector("[role=status]");
      function informar(mensaje) {
        window.MassIdioma.rotulo(estado, mensaje);
      }
      function seleccionar() {
        const rango = document.createRange();
        rango.selectNodeContents(original);
        const seleccion = window.getSelection();
        seleccion.removeAllRanges();
        seleccion.addRange(rango);
        informar("Texto seleccionado. Usa la opción Copiar de tu dispositivo.");
      }
      if (navigator.clipboard?.writeText) {
        navigator.clipboard.writeText(original.textContent).then(
          () => informar("Texto copiado."), seleccionar
        );
      } else {
        seleccionar();
      }
      return;
    }
    const enlace = evento.target.closest?.("[data-documento-mass-id]");
    if (!enlace) return;
    const doc = ficha(enlace.dataset.documentoMassId);
    const visor = document.getElementById("lecturaPublicaMassId");
    if (!doc || !visor) return;
    const titulo = visor.querySelector("h2");
    titulo.dataset.massUi = "";
    titulo.textContent = doc.titulo;
    window.MassIdioma?.aplicar?.(titulo);
    mostrar(visor.querySelector("article"), visor.querySelector("small"), doc.es);
    if (!visor.open) visor.showModal();
    visor.querySelector("article").scrollTop = 0;
  });

